//! Themes: one file per theme, looked up by name.
//!
//! The file format is Ghostty's, because it is the format the themes people
//! already have are written in — `key = value` lines, `palette = N=#rrggbb` for
//! the sixteen ANSI colours, `background`/`foreground`/`cursor-color` for the
//! rest. Reading it costs nothing and means a user can point dtr at the themes
//! they already collected instead of re-entering them.
//!
//! Rewriting it is also cheap, which matters more: a theme file is small enough
//! to keep by hand, and a format that one terminal already reads is a format
//! another one can share.

use std::fmt;
use std::path::{Path, PathBuf};

use libghostty_vt::style::{Palette, PaletteIndex, RgbColor};

/// A complete-enough theme: sixteen ANSI colours, default foreground and
/// background, and optionally a cursor colour.
#[derive(Clone, Debug, PartialEq)]
pub struct Theme {
    pub name: String,
    /// ANSI 0–15. Indices beyond 15 are generated by the VT core from these.
    pub palette: [Option<[u8; 3]>; 16],
    pub foreground: Option<[u8; 3]>,
    pub background: Option<[u8; 3]>,
    pub cursor: Option<[u8; 3]>,
}

impl Theme {
    fn empty(name: &str) -> Self {
        Self {
            name: name.to_owned(),
            palette: [None; 16],
            foreground: None,
            background: None,
            cursor: None,
        }
    }

    /// Apply to a terminal. The palette is what makes the whole 256-colour cube
    /// follow the theme rather than only the sixteen named colours.
    pub fn apply(&self, term: &mut libghostty_vt::Terminal<'_, '_>) -> anyhow::Result<()> {
        if let Some(rgb) = self.background {
            term.set_default_bg_color(Some(colour(rgb)))?;
        }
        if let Some(rgb) = self.foreground {
            term.set_default_fg_color(Some(colour(rgb)))?;
        }
        if let Some(rgb) = self.cursor {
            term.set_default_cursor_color(Some(colour(rgb)))?;
        }

        if self.palette.iter().any(Option::is_some) {
            let mut palette = term.default_color_palette()?;
            for (index, entry) in self.palette.iter().enumerate() {
                if let Some(rgb) = entry {
                    palette.set(palette_index(index as u8), colour(*rgb));
                }
            }
            term.set_default_color_palette(Some(palette))?;
        }
        Ok(())
    }
}

fn colour(rgb: [u8; 3]) -> RgbColor {
    RgbColor {
        r: rgb[0],
        g: rgb[1],
        b: rgb[2],
    }
}

fn palette_index(value: u8) -> PaletteIndex {
    // The parser is the supported way to build one of these from a number, and
    // it round-trips: `parse_palette_entry` accepts exactly this syntax.
    Palette::parse_palette_entry(&format!("{value}=#000000"))
        .map(|(index, _)| index)
        .expect("a decimal palette index in range always parses")
}

impl Theme {
    pub fn parse(name: &str, text: &str) -> Result<Self, Error> {
        let mut theme = Self::empty(name);
        for (number, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            let key = key.trim();
            let value = value.trim().trim_matches('"');

            match key {
                "palette" => {
                    let (index, rgb) = Palette::parse_palette_entry(value)
                        .map_err(|err| Error::Line(number + 1, format!("{err}")))?;
                    let slot = (index.0 as usize).min(15);
                    if (index.0 as usize) < 16 {
                        theme.palette[slot] = Some([rgb.r, rgb.g, rgb.b]);
                    }
                }
                "background" => theme.background = Some(parse_colour(value).map_err(|err| {
                    Error::Line(number + 1, format!("background: {err}"))
                })?),
                "foreground" => theme.foreground = Some(parse_colour(value).map_err(|err| {
                    Error::Line(number + 1, format!("foreground: {err}"))
                })?),
                "cursor-color" | "cursor_color" => theme.cursor = Some(
                    parse_colour(value)
                        .map_err(|err| Error::Line(number + 1, format!("cursor-color: {err}")))?,
                ),
                // Everything else in a Ghostty theme file is about fonts,
                // opacity or window chrome; ignoring it is what lets us read
                // existing themes instead of demanding our own.
                _ => {}
            }
        }
        Ok(theme)
    }

    /// The file contents for this theme, in the same format it reads.
    pub fn render(&self) -> String {
        let mut out = String::new();
        if let Some(rgb) = self.background {
            out.push_str(&format!("background = {}\n", hex(rgb)));
        }
        if let Some(rgb) = self.foreground {
            out.push_str(&format!("foreground = {}\n", hex(rgb)));
        }
        if let Some(rgb) = self.cursor {
            out.push_str(&format!("cursor-color = {}\n", hex(rgb)));
        }
        if self.palette.iter().any(Option::is_some) {
            out.push('\n');
        }
        for (index, entry) in self.palette.iter().enumerate() {
            if let Some(rgb) = entry {
                out.push_str(&format!("palette = {index}={}\n", hex(*rgb)));
            }
        }
        out
    }
}

fn hex(rgb: [u8; 3]) -> String {
    format!("#{:02x}{:02x}{:02x}", rgb[0], rgb[1], rgb[2])
}

fn parse_colour(value: &str) -> Result<[u8; 3], String> {
    let rgb = RgbColor::parse(value).map_err(|err| err.to_string())?;
    Ok([rgb.r, rgb.g, rgb.b])
}

/// Where themes are looked for, most specific first.
///
/// The Ghostty directory is last: reading themes the user already has is the
/// point, but our own directory wins if a name exists in both.
pub fn search_paths() -> Vec<PathBuf> {
    let mut paths = Vec::new();
    if let Some(config) = dirs::config_dir() {
        paths.push(config.join("dtr").join("themes"));
        paths.push(config.join("ghostty").join("themes"));
    }
    if let Some(data) = dirs::data_dir() {
        paths.push(data.join("dtr").join("themes"));
    }
    paths
}

/// Resolve a theme name to a file.
pub fn find(name: &str) -> Result<PathBuf, Error> {
    for directory in search_paths() {
        let candidate = directory.join(name);
        if candidate.is_file() {
            return Ok(candidate);
        }
    }
    Err(Error::NotFound {
        name: name.to_owned(),
        searched: search_paths(),
    })
}

/// Load a theme by name.
pub fn load(name: &str) -> Result<Theme, Error> {
    let path = find(name)?;
    let text = std::fs::read_to_string(&path).map_err(|err| Error::Io(path.clone(), err.to_string()))?;
    Theme::parse(name, &text)
}

/// Theme names available in the search paths, for the palette.
pub fn names() -> Vec<String> {
    let mut names = Vec::new();
    for directory in search_paths() {
        let Ok(entries) = std::fs::read_dir(&directory) else {
            continue;
        };
        for entry in entries.flatten() {
            if entry.path().is_file() {
                if let Some(name) = entry.file_name().to_str() {
                    names.push(name.to_owned());
                }
            }
        }
    }
    names.sort();
    names.dedup();
    names
}

#[derive(Debug)]
pub enum Error {
    NotFound {
        name: String,
        searched: Vec<PathBuf>,
    },
    Io(PathBuf, String),
    Line(usize, String),
}

impl fmt::Display for Error {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Error::NotFound { name, searched } => {
                write!(formatter, "no theme named {name:?}; looked in")?;
                for path in searched {
                    write!(formatter, " {}", path.display())?;
                }
                Ok(())
            }
            Error::Io(path, message) => write!(formatter, "{}: {message}", path.display()),
            Error::Line(number, message) => write!(formatter, "line {number}: {message}"),
        }
    }
}

impl std::error::Error for Error {}

#[cfg(test)]
mod tests {
    use super::Theme;

    const WAVE: &str = r#"
# Kanagawa Wave
background = #1f1f28
foreground = #dcd7ba
cursor-color = #c8c093

palette = 0=#1f1f28
palette = 1=#c34043
palette = 8=#54546d
palette = 15=#dcd7ba
"#;

    #[test]
    fn a_ghostty_theme_file_is_read() {
        let theme = Theme::parse("kanagawa wave", WAVE).unwrap();
        assert_eq!(theme.background, Some([0x1f, 0x1f, 0x28]));
        assert_eq!(theme.foreground, Some([0xdc, 0xd7, 0xba]));
        assert_eq!(theme.cursor, Some([0xc8, 0xc0, 0x93]));
        assert_eq!(theme.palette[0], Some([0x1f, 0x1f, 0x28]));
        assert_eq!(theme.palette[1], Some([0xc3, 0x40, 0x43]));
        assert_eq!(theme.palette[8], Some([0x54, 0x54, 0x6d]));
        assert_eq!(theme.palette[15], Some([0xdc, 0xd7, 0xba]));
        // Not set in the file, so nothing is invented.
        assert_eq!(theme.palette[2], None);
    }

    #[test]
    fn unreadable_keys_are_ignored_not_fatal() {
        // A real Ghostty theme file carries font and window settings too.
        let theme = Theme::parse(
            "x",
            "font-family = JetBrains Mono\nbackground-opacity = 0.95\nbackground = #000000\n",
        )
        .unwrap();
        assert_eq!(theme.background, Some([0, 0, 0]));
    }

    #[test]
    fn a_bad_colour_names_the_line() {
        let error = Theme::parse("x", "background = #000000\nforeground = #zzzzzz\n")
            .unwrap_err()
            .to_string();
        assert!(error.starts_with("line 2:"), "{error}");
    }

    #[test]
    fn quotes_and_spacing_are_tolerated() {
        let theme = Theme::parse("x", "  background   =   \"#101010\"  \n").unwrap();
        assert_eq!(theme.background, Some([0x10, 0x10, 0x10]));
    }

    #[test]
    fn rendering_round_trips_through_the_parser() {
        let original = Theme::parse("kanagawa wave", WAVE).unwrap();
        let again = Theme::parse("kanagawa wave", &original.render()).unwrap();
        assert_eq!(original, again);
    }
}
